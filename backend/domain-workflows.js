for (const [scenarioId, template] of Object.entries(DOMAIN_WORKFLOW_TEMPLATES)) {
  template.id = `${template.domain}.${scenarioId}.workflow`
  template.version = 1
}

export function getDomainWorkflowTemplate(domain, scenarioId) {
  const template = Object.hasOwn(DOMAIN_WORKFLOW_TEMPLATES, scenarioId) ? DOMAIN_WORKFLOW_TEMPLATES[scenarioId] : null
  return template && (!domain || template.domain === domain) ? template : null
}
