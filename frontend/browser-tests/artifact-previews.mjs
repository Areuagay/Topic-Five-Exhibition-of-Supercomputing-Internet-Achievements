import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel:'chrome', headless:true })
try {
  const page = await browser.newPage({ viewport:{ width:1366,height:1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${process.env.FRONTEND_URL || 'http://127.0.0.1:3000'}/domains/llm/runs/LLM-20260811-0001`)
  const row = name => page.locator('.el-table__row').filter({ hasText:name })
  await row('training_series.csv').getByRole('button', {name:'预览',exact:true}).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('.csv-scroll tbody tr').first().waitFor()
  assert.match(await dialog.locator('thead').innerText(), /step/)
  assert.equal(await dialog.locator('input,textarea,[contenteditable="true"]').count(), 0)
  await dialog.screenshot({ path:'../.runtime-logs/csv-preview.png' })
  await page.getByRole('button',{name:'Close this dialog'}).click()
  await row('gpu_metrics.json').getByRole('button',{name:'预览',exact:true}).click()
  await dialog.locator('pre').waitFor()
  assert.match(await dialog.locator('pre').innerText(), /gpu_id/)
  await page.getByRole('button',{name:'Close this dialog'}).click()
  await row('training_curve_4200.png').getByRole('button',{name:'预览',exact:true}).click()
  await dialog.getByText('暂时无法预览此文件').waitFor()
  await dialog.screenshot({ path:'../.runtime-logs/preview-failure.png' })
  await dialog.getByRole('button',{name:'重新加载'}).click()
  await dialog.getByText('暂时无法预览此文件').waitFor()
  await page.getByRole('button',{name:'Close this dialog'}).click()
  assert.equal(await row('checkpoint-4200').getByRole('button',{name:'预览',exact:true}).count(), 0)
  const before = (await row('checkpoint-4200').boundingBox()).height
  await row('checkpoint-4200').getByRole('button',{name:'下载',exact:true}).click()
  const failure = page.locator('.download-failure:visible')
  await failure.waitFor()
  await page.waitForTimeout(300) // Capture after the popover entrance transition.
  assert.equal((await row('checkpoint-4200').boundingBox()).height, before)
  await failure.locator('..').screenshot({ path:'../.runtime-logs/download-failure.png' })
  await page.mouse.click(10,10)
  await failure.waitFor({state:'hidden'})
  await row('checkpoint-4200').getByRole('button',{name:'下载',exact:true}).click()
  await failure.waitFor()
  await page.keyboard.press('Escape')
  await failure.waitFor({state:'hidden'})
  await row('checkpoint-4200').getByRole('button',{name:'下载',exact:true}).click()
  await failure.waitFor()
  await row('training_curve_4200.png').getByRole('button',{name:'下载',exact:true}).click()
  await page.waitForTimeout(300)
  assert.equal(await page.locator('.download-failure:visible').count(),1)
  await failure.getByRole('button',{name:'重新下载'}).click()
  await failure.waitFor()
  await failure.getByRole('button',{name:'关闭下载提示'}).click()
  // Correctly parse CSV quotes and preserve leading zeroes; no editable cells.
  await page.route('**/ART-LLM-PCSV1/preview', r => r.fulfill({ body:'id,note,value\r\n001,"a,b\nsecond line",0\r\n',contentType:'text/csv' }))
  await row('training_series.csv').getByRole('button',{name:'预览',exact:true}).click()
  await dialog.getByRole('cell',{name:'001',exact:true}).waitFor()
  assert.match(await dialog.locator('tbody').innerText(), /a,b\nsecond line/)
  await page.getByRole('button',{name:'Close this dialog'}).click()
  await page.unroute('**/ART-LLM-PCSV1/preview')
  await page.route('**/ART-LLM-PCSV1/preview', r => r.fulfill({ body:'value\n'+Array.from({length:160},(_,i) => String((i+1)/20)).join('\n'),contentType:'text/csv' }))
  await row('training_series.csv').getByRole('button',{name:'预览',exact:true}).click()
  const lastRow = dialog.locator('tbody tr').last()
  await lastRow.waitFor()
  await dialog.locator('.csv-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
  assert.equal(await lastRow.locator('th').innerText(), '160')
  assert.ok((await lastRow.boundingBox()).height <= 44)
  assert.equal(await lastRow.locator('th').evaluate(el => getComputedStyle(el).whiteSpace), 'nowrap')
  await dialog.screenshot({path:'../.runtime-logs/csv-three-digit-rows.png'})
  assert.deepEqual(errors, [])
  console.log('PASS: readonly CSV, quoted fields, JSON text, preview retry, download popover, unchanged row height, download-only binaries')
} finally { await browser.close() }
