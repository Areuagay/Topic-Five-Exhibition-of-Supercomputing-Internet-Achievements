import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { createHash } from 'node:crypto'
import { readFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.FRONTEND_URL || 'http://localhost:3000'
const output = resolve(import.meta.dirname, '../../.runtime-data/logs')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 }, reducedMotion: 'reduce' })
  page.setDefaultTimeout(30000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const geoPath = '/domains/geodynamics/runs/GEO-20260811-0009'
  await page.goto(base + geoPath)
  const measured = page.locator('.measured-results')
  await measured.waitFor()
  assert.ok((await measured.textContent()).includes('117,649'))
  assert.equal(await page.locator('.run-data-panel').count(), 0)
  await measured.getByRole('button', { name: '速度模长', exact: true }).click()
  assert.ok((await measured.textContent()).includes('1,378.041'))
  await measured.locator('canvas').waitFor()
  await measured.screenshot({ path: resolve(output, 'measured-geodynamics.png') })
  await measured.getByText('查看提供方原始结果图', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.measured-disclosure img')?.naturalWidth > 0)
  const zipRow = measured.locator('.el-table__row').filter({ hasText: '地球动力_结果.zip' })
  const downloadPromise = page.waitForEvent('download')
  await zipRow.getByRole('button', { name: '下载', exact: true }).click()
  const download = await downloadPromise
  assert.equal(download.suggestedFilename(), '地球动力_结果.zip')
  const source = readFileSync(resolve(import.meta.dirname, '../../artifacts/provided/地球动力_结果.zip'))
  const downloaded = readFileSync(await download.path())
  assert.equal(createHash('sha256').update(downloaded).digest('hex'), createHash('sha256').update(source).digest('hex'))
  await page.getByRole('button', { name: '当前任务数据', exact: true }).click()
  await page.locator('.run-data-panel').waitFor()
  assert.equal(await measured.count(), 0)
  await page.getByRole('button', { name: '实测算例结果', exact: true }).click()
  await measured.waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await measured.screenshot({ path: resolve(output, 'measured-geodynamics-mobile.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)

  await page.setViewportSize({ width: 1500, height: 1000 })
  await page.goto(`${base}/domains/llm/runs/LLM-20260811-0001`)
  await measured.waitFor()
  assert.equal(await measured.locator('.operator-controls button').count(), 4)
  await measured.getByRole('button', { name: 'transformers-trainer', exact: true }).click()
  assert.ok((await measured.textContent()).includes('98.73'))
  await measured.getByRole('button', { name: 'peft-lora', exact: true }).click()
  assert.ok((await measured.textContent()).includes('1.3928'))
  await measured.getByRole('button', { name: 'pytorch-ddp', exact: true }).click()
  assert.ok((await measured.textContent()).includes('62.81'))
  assert.ok((await measured.textContent()).includes('51.65'))
  await measured.getByRole('button', { name: '试验 3', exact: true }).click()
  assert.equal(await measured.getByRole('button', { name: '试验 3', exact: true }).getAttribute('aria-pressed'), 'true')
  await measured.getByText('查看算子原始日志', { exact: true }).click()
  assert.ok((await measured.locator('pre').first().textContent()).includes('trial=3 baseline=68.42s'))
  await measured.screenshot({ path: resolve(output, 'measured-training.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => [...document.querySelectorAll('.measured-results canvas')].every(canvas => canvas.getBoundingClientRect().right <= document.querySelector('.measured-body').getBoundingClientRect().right))
  await measured.screenshot({ path: resolve(output, 'measured-training-mobile.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)

  await page.goto(`${base}/domains/uav/runs/UAV-20260923-0018`)
  await page.locator('.run-data-panel').waitFor()
  assert.equal(await measured.count(), 0)
  assert.equal(await page.locator('.scenario-videos').count(), 1)
  const nonexistent = await page.request.get(`${base}/api/v1/llm/runs/missing/measured-result`)
  assert.equal(nonexistent.status(), 404)
  await page.route('**/api/v1/geodynamics/runs/*/measured-result', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: 'temporary failure' }) }))
  await page.goto(base + geoPath)
  await page.getByText('实测算例结果加载失败', { exact: true }).waitFor()
  assert.equal(await measured.count(), 0)
  await page.unroute('**/api/v1/geodynamics/runs/*/measured-result')
  await page.locator('.resource-state').filter({ hasText: '实测算例结果加载失败' }).getByRole('button', { name: '重试', exact: true }).click()
  await measured.waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: measured scenes, four operators, trial switch, original files, source toggle, mobile layout, scene isolation and retry')
} finally { await browser.close() }
